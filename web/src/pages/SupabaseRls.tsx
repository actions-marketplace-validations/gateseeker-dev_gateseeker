/**
 * /supabase-rls: the page for the most common way AI-built apps leak data
 * (docs/SPRINT_9.md). It says what Gateseeker checks, and just as plainly
 * what it cannot see from a repository, with read-only SQL to check the rest.
 * The incident is cited from its public CVE record, nothing more.
 */

const TABLES_SQL = `-- Read-only: lists your tables and whether Row Level Security is on.
select c.relname as table_name, c.relrowsecurity as rls_on
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relkind = 'r'
order by c.relrowsecurity, c.relname;`;

const POLICIES_SQL = `-- Read-only: lists the policies. "true" as the condition for anon
-- or public means everyone with the anon key gets those rows.
select tablename, policyname, cmd, roles, qual, with_check
from pg_policies
where schemaname = 'public'
order by tablename, policyname;`;

const FIX_SQL = `alter table public.profiles enable row level security;

-- Each person reads and changes only their own row.
create policy "own profile" on public.profiles
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);`;

